// ?lang= d'abord, puis le choix des Réglages, puis ELI_LANG du serveur, puis le navigateur (fr → fr, le reste → en).
export function pickLang({ query, saved, server, nav } = {}) {
  for (const l of [query, saved, server]) if (l === 'fr' || l === 'en') return l;
  return String(nav || '').toLowerCase().startsWith('fr') ? 'fr' : 'en';
}

export let lang = 'fr';
export function setLang(l) {
  lang = l === 'en' ? 'en' : 'fr';
  if (typeof document !== 'undefined') document.documentElement.lang = lang;
}

export function t(fr, vars = {}) {
  const s = (lang === 'en' && EN[fr]) || fr;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

// Retraduit la page sur place, dans un sens comme dans l'autre : un texte déjà anglais retrouve sa clé française
// (FR), ce qui rend l'appel rejouable et rattrape les textes posés par le JS. Seules les correspondances exactes changent.
const FR = Object.fromEntries(Object.entries(EN).map(([fr, en]) => [en, fr]));
const ATTRS = ['placeholder', 'title', 'aria-label', 'data-empty'];
const swap = (s) => {
  const k = s.trim();
  return k ? s.replace(k, () => t(FR[k] ?? k)) : s;
};
export function translateDom(root) {
  const walk = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  for (let n = walk.currentNode; n; n = walk.nextNode()) {
    if (n.nodeType === Node.TEXT_NODE) {
      const v = swap(n.nodeValue);
      if (v !== n.nodeValue) n.nodeValue = v;
    } else {
      for (const a of ATTRS) if (n.hasAttribute(a)) n.setAttribute(a, swap(n.getAttribute(a)));
    }
  }
}
